test('vendor: every stub is documented with its reason and bindings', () => {
  const m = manifest();
  for (const s of m.stubs) {
    assert.ok(s.reason && s.reason.length > 3, `${s.path} has a reason`);
    assert.ok(Array.isArray(s.importedBy) && s.importedBy.length > 0, `${s.path} records who imports it`);
    const body = fs.readFileSync(path.join(VENDOR_DIR, s.path), 'utf8');
    assert.match(body, /GENERATED by tools\/vendor-upstream\.mjs/);
    assert.match(body, /const inert = /);
  }
});

test('vendor: the upstream licence and README are preserved', () => {
  for (const name of ['LICENSE.upstream', 'LICENSE.upstream.md']) {
    const file = path.join(VENDOR_DIR, name);
    assert.ok(fs.existsSync(file), `${name} exists`);
  }
  const licence = fs.readFileSync(path.join(VENDOR_DIR, 'LICENSE.upstream'), 'utf8');
  assert.match(licence, /MIT License/);
  assert.match(licence, /Lattymoy/);
});

test('vendor: the subset loads and the overhaul installs', async () => {
  const u = await upstream();
  assert.equal(typeof u.combatStats.computeCombatStats, 'function');
  assert.equal(typeof u.pcaao.pcaaoAttackDamage, 'function');
  assert.equal(typeof u.bossTraits.bossStrike, 'function');
  // The install is live: the classic strength term now reads the overhaul's /10.
  assert.equal(u.formulas.damageModifier(80), u.pcaao.pcaaoDamageModifier(80));
});

test('vendor: the subset is a small fraction of the client it is cut from', () => {
  // A guard against someone "fixing" a stub by vendoring the whole game.
  const m = manifest();
  const bytes = [...m.files, ...m.stubs].reduce((n, r) => {
    const file = path.join(VENDOR_DIR, r.path);
    return n + (fs.existsSync(file) ? fs.statSync(file).size : 0);
  }, 0);
  assert.ok(bytes < 12 * 1024 * 1024, `vendored bytes ${(bytes / 1e6).toFixed(1)} MB under the 12 MB ceiling`);
  assert.ok(m.stubs.length < m.files.length, 'the cut edges stay a minority');
});

test('vendor: the source maps back to the documented upstream paths', () => {
  const m = manifest();
  for (const f of m.files) {
    assert.equal(f.path, f.upstream, `${f.path} keeps its upstream path`);
    // Upstream paths under src/ (modules) or vendor/ (data files the modules import whole).
    assert.match(f.upstream, /^(src|vendor)\//, f.upstream);
  }
  assert.ok(fs.existsSync(path.join(SRC, 'combat/pcaao.js')));
});
