/*
 * test/vendor-manifest.test.js - the vendored game implementation is exactly
 * what the manifest says it is.
 *
 * The differential suite is only as good as its oracle, so this file fails if:
 *   - a vendored file was edited (byte hash differs from MANIFEST.json),
 *   - a file appeared or vanished without the manifest knowing,
 *   - the manifest pins a different commit than the harness expects,
 *   - a stubbed edge crept into a module the harness measures,
 *   - the vendored modules no longer load.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

import { COMMIT, VENDOR_DIR, SRC, manifest, upstream } from './harness/upstream.mjs';
import { verify } from '../tools/vendor-upstream.mjs';

test('vendor: the manifest pins the audited commit and comes from the vendor tool', () => {
  const m = manifest();
  assert.equal(m.upstream.commit, COMMIT);
  assert.equal(m.upstream.repo, 'Lattymoy/daggerfall-js-source');
  assert.equal(m.generatedBy, 'tools/vendor-upstream.mjs');
  assert.ok(m.files.length > 80, `vendored files: ${m.files.length}`);
  assert.ok(m.stubs.length > 0, 'the cut edges are recorded, not hidden');
});

test('vendor: every file matches its recorded hash, and nothing extra exists', () => {
  const { problems } = verify();
  assert.deepEqual(problems, [], problems.join('\n'));
});

test('vendor: every recorded file is present and hashed, with no duplicates', () => {
  const m = manifest();
  const seen = new Set();
  for (const row of [...m.files, ...m.stubs]) {
    assert.match(row.sha256, /^[0-9a-f]{64}$/, `${row.path} has a sha256`);
    assert.ok(!seen.has(row.path), `${row.path} listed once`);
    seen.add(row.path);
    assert.ok(fs.existsSync(path.join(VENDOR_DIR, row.path)), `${row.path} exists`);
  }
  for (const row of m.files) assert.equal(row.role, 'vendored');
  for (const row of m.stubs) assert.equal(row.role, 'stub');
});

test('vendor: a modified vendored file is detected (tamper check is live)', () => {
  const m = manifest();
  const file = path.join(VENDOR_DIR, m.files[0].path);
  const original = fs.readFileSync(file);
  try {
    fs.appendFileSync(file, '\n// tamper\n');
    const { problems } = verify();
    assert.ok(
      problems.some((p) => p.includes(m.files[0].path) && /modified/.test(p)),
      `a one-line edit is reported (${problems.join('; ') || 'nothing reported'})`,
    );
  } finally {
    fs.writeFileSync(file, original);
  }
  assert.deepEqual(verify().problems, [], 'the tree is restored');
});

